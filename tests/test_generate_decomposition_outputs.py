"""Tests for the composition-decomposition publication outputs."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from scripts.generate_decomposition_outputs import generate_outputs


ROOT = Path(__file__).resolve().parents[1]


class CompositionDecompositionPublicationTest(unittest.TestCase):
    def test_generates_outputs_from_verified_results(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            target = Path(temporary)
            outputs = generate_outputs(
                result_dir=ROOT / "data/results/decomposition",
                manifest_path=ROOT / "data/results/manifests/16_composition_decomposition.json",
                table_dir=target / "tables",
                figure_dir=target / "figures",
            )
            self.assertEqual(len(outputs), 3)
            for path in outputs.values():
                self.assertTrue(path.exists())
                self.assertGreater(path.stat().st_size, 300)
                self.assertTrue(path.read_text(encoding="utf-8").startswith("% Generated by scripts/generate_decomposition_outputs.py"))
            table = outputs["common_weight_table"].read_text(encoding="utf-8")
            self.assertIn("Average AU--NZ decision shares", table)
            self.assertIn("Rate component", table)
            self.assertIn("Composition component", table)
            self.assertIn("not causal effects", table)
            self.assertIn("$p=", table)
            self.assertIn(r"\resizebox{\textwidth}{!}{%", table)
            composition = outputs["annual_composition_table"].read_text(encoding="utf-8")
            self.assertIn("2022 & Australia", composition)
            self.assertIn("2025 & New Zealand", composition)
            self.assertIn(r"\begin{tabular*}{\textwidth}", composition)
            self.assertIn(r"\extracolsep{\fill}", composition)
            self.assertNotIn(r"\resizebox", composition)
            figure = outputs["decomposition_figure"].read_text(encoding="utf-8")
            self.assertIn("Observed matched-support gap", figure)
            self.assertIn("Rate component", figure)
            self.assertIn("Composition component", figure)
            self.assertIn(r"width=0.88\textwidth", figure)
            self.assertIn("legend columns=2", figure)


if __name__ == "__main__":
    unittest.main()
