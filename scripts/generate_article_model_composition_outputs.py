#!/usr/bin/env python3
"""Generate the manuscript's applicant-origin composition table and figure."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(path: Path) -> None:
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("module") != "src.analysis_08_origin_composition" or value.get("status") != "passed":
        raise ValueError(f"{path}: origin-composition analysis did not pass")
    for output in value["outputs"]:
        target = ROOT / output["path"]
        if not target.exists() or sha256(target) != output["sha256"]:
            raise ValueError(f"{path}: output hash mismatch for {target}")


def p_format(value: str) -> str:
    number = float(value)
    return "$p<0.001$" if number < 0.001 else f"$p={number:.3f}$"


def coordinates(
    source: list[dict[str, str]], x: str, y: str
) -> str:
    return " ".join(
        f"({float(row[x]):.12g},{float(row[y]):.12g})" for row in source
    )


def generate_outputs(
    *,
    composition_dir: Path = ROOT / "data/results/composition",
    manifest_dir: Path = ROOT / "data/results/manifests",
    table_dir: Path = ROOT / "article/tables",
    figure_dir: Path = ROOT / "article/figures",
) -> dict[str, Path]:
    verify_manifest(manifest_dir / "08_origin_composition.json")
    concentration_rows = rows(composition_dir / "concentration_statistics.csv")
    concordance_rows = rows(composition_dir / "share_concordance.csv")
    ranked = rows(composition_dir / "ranked_share_points.csv")
    lorenz = rows(composition_dir / "lorenz_curve_points.csv")
    distance = rows(composition_dir / "composition_distance.csv")
    if len(distance) != 1 or distance[0].get("eligible") != "false":
        raise ValueError("composition-distance skip is missing or inconsistent")

    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "composition_table": table_dir / "origin_composition_statistics.tex",
        "composition_curves": figure_dir / "origin_composition_curves.tex",
    }

    lines = [
        "% Generated by scripts/generate_article_model_composition_outputs.py. Do not edit.",
        r"\begin{table}",
        r"\caption{Applicant-origin composition and concentration of recorded decisions, 2022--2025}",
        r"\label{tab:origin-composition}",
        r"\centering",
        r"\small",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrr@{}}",
        r"\toprule",
        r"Destination & Origins & Top 1 & Top 5 & Top 10 & HHI & Gini \\",
        r"\midrule",
    ]
    for row in concentration_rows:
        lines.append(
            f"{row['destination_country']} & {row['represented_origins']} & "
            f"{float(row['top_1_share']) * 100:.1f}\\% & "
            f"{float(row['top_5_share']) * 100:.1f}\\% & "
            f"{float(row['top_10_share']) * 100:.1f}\\% & "
            f"{float(row['hhi_0_1']):.3f} & {float(row['gini']):.3f} " + r"\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\vspace{0.4em}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrr@{}}",
        r"\toprule",
        r"Matched-share measure & Coefficient & 95\% CI & Two-sided $p$ \\",
        r"\midrule",
    ]
    for row in concordance_rows:
        lines.append(
            f"{row['method']} & {float(row['coefficient']):.3f} & "
            f"[{float(row['ci_lower']):.3f}, {float(row['ci_upper']):.3f}] & "
            f"{p_format(row['p_value'])} " + r"\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\parbox{0.96\textwidth}{\scriptsize Notes: Shares use each destination's complete recorded decision total. HHI is on the 0--1 scale. Jensen--Shannon divergence was not calculated because the missingness audit did not permit absent origins to be assigned zero.}",
        r"\end{table}",
    ]
    outputs["composition_table"].write_text("\n".join(lines) + "\n", encoding="utf-8")

    au_rank = [row for row in ranked if row["destination_code"] == "AU"]
    nz_rank = [row for row in ranked if row["destination_code"] == "NZ"]
    au_lorenz = [row for row in lorenz if row["destination_code"] == "AU"]
    nz_lorenz = [row for row in lorenz if row["destination_code"] == "NZ"]
    figure = rf"""% Generated by scripts/generate_article_model_composition_outputs.py. Do not edit.
\begin{{minipage}}[t]{{0.48\textwidth}}
\centering
\begin{{tikzpicture}}
\begin{{semilogyaxis}}[width=0.92\linewidth,height=5.4cm,xmin=1,xmax=200,ymin=0.000001,ymax=0.5,xlabel={{Origin rank}},ylabel={{Decision share}},title={{(a) Ranked shares}},legend style={{font=\scriptsize,at={{{{(0.97,0.97)}}}},anchor=north east,draw=none}},tick label style={{font=\small}},label style={{font=\small}},title style={{font=\small}}]
\addplot[blue!80!black,thick] coordinates {{{coordinates(au_rank, 'rank', 'decision_share')}}};\addlegendentry{{Australia}}
\addplot[orange!85!black,thick,dashed] coordinates {{{coordinates(nz_rank, 'rank', 'decision_share')}}};\addlegendentry{{New Zealand}}
\end{{semilogyaxis}}
\end{{tikzpicture}}
\end{{minipage}}%
\hfill
\begin{{minipage}}[t]{{0.48\textwidth}}
\centering
\begin{{tikzpicture}}
\begin{{axis}}[width=0.92\linewidth,height=5.4cm,xmin=0,xmax=1,ymin=0,ymax=1,xlabel={{Cumulative share of origins}},ylabel={{Cumulative share of decisions}},title={{(b) Lorenz curves}},legend style={{font=\scriptsize,at={{{{(0.03,0.97)}}}},anchor=north west,draw=none}},tick label style={{font=\small}},label style={{font=\small}},title style={{font=\small}}]
\addplot[gray!65,dashed,domain=0:1,forget plot] {{x}};
\addplot[blue!80!black,thick] coordinates {{{coordinates(au_lorenz, 'cumulative_origin_fraction', 'cumulative_decision_share')}}};\addlegendentry{{Australia}}
\addplot[orange!85!black,thick,dashed] coordinates {{{coordinates(nz_lorenz, 'cumulative_origin_fraction', 'cumulative_decision_share')}}};\addlegendentry{{New Zealand}}
\end{{axis}}
\end{{tikzpicture}}
\end{{minipage}}
"""
    outputs["composition_curves"].write_text(figure, encoding="utf-8")
    return outputs


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    outputs = generate_outputs()
    print("Article composition outputs written:")
    for path in outputs.values():
        print(f"- {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
