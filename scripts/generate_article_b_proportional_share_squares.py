#!/usr/bin/env python3
"""Generate the manuscript's proportional applicant-origin share squares."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(manifest_path: Path, ranked_path: Path) -> None:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("module") != "src.analysis_08_origin_composition" or manifest.get("status") != "passed":
        raise ValueError(f"{manifest_path}: Section 8 analysis did not pass")
    relative = str(ranked_path.relative_to(ROOT))
    matches = [item for item in manifest.get("outputs", []) if item.get("path") == relative]
    if len(matches) != 1 or matches[0].get("sha256") != sha256(ranked_path):
        raise ValueError(f"{manifest_path}: ranked-share input hash mismatch")


def read_ranked_shares(path: Path) -> dict[str, list[dict[str, float | int | str]]]:
    grouped: dict[str, list[dict[str, float | int | str]]] = {"AU": [], "NZ": []}
    with path.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            code = row["destination_code"]
            if code not in grouped:
                raise ValueError(f"unexpected destination code: {code}")
            grouped[code].append(
                {
                    "rank": int(row["rank"]),
                    "country": row["country"],
                    "decision_share": float(row["decision_share"]),
                }
            )
    for code, destination_rows in grouped.items():
        destination_rows.sort(key=lambda row: int(row["rank"]))
        if [int(row["rank"]) for row in destination_rows] != list(
            range(1, len(destination_rows) + 1)
        ):
            raise ValueError(f"{code}: ranks are not contiguous")
        shares = [float(row["decision_share"]) for row in destination_rows]
        if shares != sorted(shares, reverse=True) or min(shares) <= 0:
            raise ValueError(f"{code}: shares are not positive descending values")
        if not math.isclose(sum(shares), 1.0, rel_tol=0, abs_tol=1e-12):
            raise ValueError(f"{code}: shares do not sum to one")
    return grouped


def square_commands(
    rows: list[dict[str, float | int | str]],
    *,
    baseline: float,
    maximum: float,
    style: str,
) -> tuple[list[str], float, float]:
    commands: list[str] = []
    cursor = 0.0
    area = 0.0
    for row in rows:
        side = math.sqrt(float(row["decision_share"]) / maximum)
        commands.append(
            rf"\filldraw[{style},draw=white,line width=0.12pt] ({cursor:.9f},{baseline:.9f}) rectangle ({cursor + side:.9f},{baseline + side:.9f});"
        )
        cursor += side
        area += side * side
    return commands, cursor, area


def generate(
    *,
    ranked_path: Path = ROOT / "data/results/composition/ranked_share_points.csv",
    manifest_path: Path = ROOT / "data/results/manifests/08_origin_composition.json",
    output_tex: Path = ROOT / "article/figures/origin_share_proportional_squares.tex",
) -> dict[str, Path | float]:
    verify_manifest(manifest_path, ranked_path)
    ranked = read_ranked_shares(ranked_path)
    maximum = max(
        float(row["decision_share"])
        for destination_rows in ranked.values()
        for row in destination_rows
    )
    au_commands, au_width, au_area = square_commands(
        ranked["AU"], baseline=1.35, maximum=maximum, style="fill=blue!72!black"
    )
    nz_commands, nz_width, nz_area = square_commands(
        ranked["NZ"], baseline=0.25, maximum=maximum, style="fill=orange!88!black"
    )
    plot_width = max(au_width, nz_width)
    source = rf"""% Generated by scripts/generate_article_b_proportional_share_squares.py. Do not edit.
% Every square has side sqrt(origin share / largest origin share), so its area
% is proportional to that origin's share of its destination's decisions.
\begin{{tikzpicture}}[x={{0.80\textwidth/{plot_width:.9f}}},y=1.45cm]
\node[font=\small,anchor=east] at (-0.12,1.65) {{Australia}};
\node[font=\small,anchor=east] at (-0.12,0.45) {{New Zealand}};
{chr(10).join(au_commands)}
{chr(10).join(nz_commands)}
\draw[->,thin] (0,0.08) -- ({plot_width:.9f},0.08);
\node[font=\small,anchor=north] at ({plot_width / 2:.9f},0.02) {{Origins ordered from largest to smallest decision share}};
\end{{tikzpicture}}
"""
    output_tex.parent.mkdir(parents=True, exist_ok=True)
    output_tex.write_text(source, encoding="utf-8")
    return {
        "tex": output_tex,
        "maximum": maximum,
        "au_width": au_width,
        "nz_width": nz_width,
        "au_area": au_area,
        "nz_area": nz_area,
    }


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    outputs = generate()
    print("Proportional-share-square figure written:")
    print(f"- {Path(outputs['tex']).relative_to(ROOT)}")
    print(f"Largest square represents {float(outputs['maximum']) * 100:.1f}% of decisions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
