#!/usr/bin/env python3
"""Generate the manuscript's annual destination table and matched-origin figure."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(path: Path) -> None:
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("module") != "src.analysis_09_temporal" or value.get("status") != "passed":
        raise ValueError(f"{path}: temporal analysis did not pass")
    for output in value["outputs"]:
        target = ROOT / output["path"]
        if not target.exists() or sha256(target) != output["sha256"]:
            raise ValueError(f"{path}: output hash mismatch for {target}")


def error_coordinates(
    source: list[dict[str, str]],
    x: str,
    estimate: str,
    lower: str,
    upper: str,
    scale: float = 1.0,
) -> str:
    output = []
    for row in source:
        value = float(row[estimate]) * scale
        low = float(row[lower]) * scale
        high = float(row[upper]) * scale
        output.append(
            f"({row[x]},{value:.12g}) += (0,{high - value:.12g}) "
            f"-= (0,{value - low:.12g})"
        )
    return " ".join(output)


def generate_outputs(
    *,
    temporal_dir: Path = ROOT / "data/results/temporal",
    manifest_dir: Path = ROOT / "data/results/manifests",
    table_dir: Path = ROOT / "article/tables",
    figure_dir: Path = ROOT / "article/figures",
) -> dict[str, Path]:
    verify_manifest(manifest_dir / "09_temporal.json")
    annual = rows(temporal_dir / "annual_destination_summary.csv")
    annual_differences = rows(temporal_dir / "annual_matched_difference_summary.csv")
    by_key = {(row["year"], row["destination_code"]): row for row in annual}

    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "destination_table": table_dir / "annual_destination_summary.tex",
        "matched_differences_figure": figure_dir / "annual_matched_differences.tex",
    }

    table_lines = [
        "% Generated by scripts/generate_article_temporal_sensitivity_outputs.py. Do not edit.",
        r"\begin{table}",
        r"\caption{Annual destination scale and approval-rate summaries}",
        r"\label{tab:annual-destination-summary}",
        r"\centering",
        r"\small",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrr@{}}",
        r"\toprule",
        r"Year & AU decisions & NZ decisions & AU aggregate & NZ aggregate & AU median & NZ median \\",
        r"\midrule",
    ]
    for year in sorted({row["year"] for row in annual_differences}):
        au = by_key[(year, "AU")]
        nz = by_key[(year, "NZ")]
        table_lines.append(
            f"{year} & {int(au['decision_total']):,} & {int(nz['decision_total']):,} & "
            f"{float(au['aggregate_approval_rate']) * 100:.1f}\\% & "
            f"{float(nz['aggregate_approval_rate']) * 100:.1f}\\% & "
            f"{float(au['median_country_approval_rate']) * 100:.1f}\\% & "
            f"{float(nz['median_country_approval_rate']) * 100:.1f}\\% " + r"\\"
        )
    table_lines += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\parbox{0.96\textwidth}{\scriptsize Notes: Aggregate rates weight recorded decisions. Median rates weight represented origins equally. All rates use the common two-outcome decision denominator.}",
        r"\end{table}",
    ]
    outputs["destination_table"].write_text(
        "\n".join(table_lines) + "\n", encoding="utf-8"
    )

    mean_coordinates = error_coordinates(
        annual_differences,
        "year",
        "mean_difference",
        "mean_ci_lower",
        "mean_ci_upper",
        100,
    )
    median_coordinates = error_coordinates(
        annual_differences,
        "year",
        "median_difference",
        "median_bootstrap_ci_lower",
        "median_bootstrap_ci_upper",
        100,
    )
    figure = rf"""% Generated by scripts/generate_article_temporal_sensitivity_outputs.py. Do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[width=0.78\textwidth,height=6.2cm,xtick={{{{2022,2023,2024,2025}}}},xticklabels={{{{2022,2023,2024,2025}}}},xlabel={{Year}},ylabel={{AU-minus-NZ rate difference (percentage points)}},ymajorgrids=true,legend style={{font=\scriptsize,draw=none,at={{{{(0.03,0.97)}}}},anchor=north west}},label style={{font=\small}},tick label style={{font=\small}}]
\addplot[gray!65,dashed,domain=2021.8:2025.2,forget plot] {{0}};
\addplot+[blue!80!black,thick,mark=*,error bars/.cd,y dir=both,y explicit] coordinates {{{mean_coordinates}}};\addlegendentry{{Mean (Student-$t$ CI)}}
\addplot+[red!80!black,thick,mark=square*,error bars/.cd,y dir=both,y explicit] coordinates {{{median_coordinates}}};\addlegendentry{{Median (bootstrap CI)}}
\end{{axis}}
\end{{tikzpicture}}
"""
    outputs["matched_differences_figure"].write_text(figure, encoding="utf-8")
    return outputs


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    outputs = generate_outputs()
    print("Article temporal outputs written:")
    for path in outputs.values():
        print(f"- {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
