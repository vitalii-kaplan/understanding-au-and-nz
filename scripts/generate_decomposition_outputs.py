#!/usr/bin/env python3
"""Generate decomposition tables and a figure from verified results."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def verify_manifest(manifest_path: Path, result_dir: Path) -> None:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("module") != "src.analysis_16_composition_decomposition" or manifest.get("status") != "passed":
        raise ValueError(f"{manifest_path}: composition-decomposition analysis did not pass")
    registered = {Path(item["path"]).name: item["sha256"] for item in manifest.get("outputs", [])}
    required = {
        "common_weight_standardisation.csv",
        "rate_composition_decomposition.csv",
        "annual_composition_statistics.csv",
    }
    if not required.issubset(registered):
        raise ValueError(f"{manifest_path}: required decomposition outputs are not registered")
    for name in required:
        path = result_dir / name
        if not path.exists() or sha256(path) != registered[name]:
            raise ValueError(f"{path}: missing or inconsistent with the analysis manifest")


def percent(value: str) -> str:
    return f"{float(value) * 100:.1f}"


def interval(row: dict[str, str], estimate: str, lower: str, upper: str) -> str:
    return f"{percent(row[estimate])} ({percent(row[lower])}, {percent(row[upper])})"


def p_value(value: str) -> str:
    number = float(value)
    return "<0.001" if number < 0.001 else f"{number:.3f}"


def effect_with_p(
    row: dict[str, str], estimate: str, lower: str, upper: str, p_field: str
) -> str:
    formatted = p_value(row[p_field])
    p_text = f"$p{formatted}$" if formatted.startswith("<") else f"$p={formatted}$"
    return f"{interval(row, estimate, lower, upper)}; {p_text}"


def generate_outputs(
    *, result_dir: Path, manifest_path: Path, table_dir: Path, figure_dir: Path
) -> dict[str, Path]:
    verify_manifest(manifest_path, result_dir)
    standards = rows(result_dir / "common_weight_standardisation.csv")
    decompositions = rows(result_dir / "rate_composition_decomposition.csv")
    compositions = rows(result_dir / "annual_composition_statistics.csv")
    pooled_standards = [
        row for row in standards
        if row["scope"] == "pooled" and row["minimum_decisions_each"] == "0"
    ]
    scheme_labels = {
        "observed_destination_specific": "Observed destination-specific weights",
        "average_destination_shares": "Average AU--NZ decision shares",
        "australia_shares": "Australian decision shares",
        "new_zealand_shares": "New Zealand decision shares",
        "equal_origin": "Equal origin weights",
    }
    pooled_standards.sort(key=lambda row: list(scheme_labels).index(row["weight_scheme"]))
    pooled_decomposition = next(
        row for row in decompositions
        if row["scope"] == "pooled" and row["minimum_decisions_each"] == "0"
    )
    annual_decomposition = sorted(
        (row for row in decompositions
         if row["scope"] == "annual_year_specific" and row["minimum_decisions_each"] == "0"),
        key=lambda row: int(row["year"]),
    )

    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    standards_path = table_dir / "common_weight_decomposition.tex"
    annual_composition_path = table_dir / "annual_composition_statistics.tex"
    figure_path = figure_dir / "annual_decomposition_components.tex"

    lines = [
        "% Generated by scripts/generate_decomposition_outputs.py. Do not edit.",
        r"\begin{table}",
        r"\caption{Pooled approval rates under observed and common applicant-origin weights}",
        r"\label{tab:common-weight-standardisation}",
        r"\centering", r"\small",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lrrr}", r"\toprule",
        r"Weight distribution & Australia, \% & New Zealand, \% & AU minus NZ, pp (95\% CI); $p$ \\",
        r"\midrule",
    ]
    for row in pooled_standards:
        lines.append(
            f"{scheme_labels[row['weight_scheme']]} & {percent(row['au_standardised_rate'])} & "
            f"{percent(row['nz_standardised_rate'])} & "
            f"{effect_with_p(row, 'au_minus_nz_difference', 'difference_ci_lower', 'difference_ci_upper', 'difference_bootstrap_p_value')} \\\\"
        )
    lines += [
        r"\bottomrule", r"\end{tabular}%", r"}",
        r"\parbox{0.96\textwidth}{\scriptsize Notes: All estimates use the 173 origins observed in both destinations. The observed row uses each destination's own decision shares. Common-weight rows apply the same stated origin distribution to both destinations. Bootstrap intervals resample origins. Two-sided bootstrap $p$-values double the smaller empirical tail probability around zero and use a plus-one correction in each tail. pp denotes percentage points.}",
        r"\end{table}", "",
        r"\begin{table}",
        r"\caption{Symmetric decomposition of the observed Australia--New Zealand aggregate approval-rate difference}",
        r"\label{tab:rate-composition-decomposition}",
        r"\centering", r"\small",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{lrrrr}", r"\toprule",
        r"Period & Origins & Observed gap, pp (95\% CI); $p$ & Rate component, pp (95\% CI); $p$ & Composition component, pp (95\% CI); $p$ \\",
        r"\midrule",
        f"2022--2025 & {pooled_decomposition['n_origins']} & "
        f"{effect_with_p(pooled_decomposition, 'observed_gap', 'observed_gap_ci_lower', 'observed_gap_ci_upper', 'observed_gap_bootstrap_p_value')} & "
        f"{effect_with_p(pooled_decomposition, 'rate_component', 'rate_component_ci_lower', 'rate_component_ci_upper', 'rate_component_bootstrap_p_value')} & "
        f"{effect_with_p(pooled_decomposition, 'composition_component', 'composition_component_ci_lower', 'composition_component_ci_upper', 'composition_component_bootstrap_p_value')} \\\\ ",
    ]
    for row in annual_decomposition:
        lines.append(
            f"{row['year']} & {row['n_origins']} & "
            f"{effect_with_p(row, 'observed_gap', 'observed_gap_ci_lower', 'observed_gap_ci_upper', 'observed_gap_bootstrap_p_value')} & "
            f"{effect_with_p(row, 'rate_component', 'rate_component_ci_lower', 'rate_component_ci_upper', 'rate_component_bootstrap_p_value')} & "
            f"{effect_with_p(row, 'composition_component', 'composition_component_ci_lower', 'composition_component_ci_upper', 'composition_component_bootstrap_p_value')} \\\\"
        )
    lines += [
        r"\bottomrule", r"\end{tabular}%", r"}",
        r"\parbox{0.96\textwidth}{\scriptsize Notes: Values are percentage points. The rate component applies average AU--NZ origin shares to origin-specific rate differences. The composition component applies decision-share differences to average origin-specific rates. Their sum reproduces the observed matched-support gap. Two-sided bootstrap $p$-values double the smaller empirical tail probability around zero and use a plus-one correction in each tail. Components are descriptive accounting quantities, not causal effects.}",
        r"\end{table}", "",
    ]
    standards_path.write_text("\n".join(lines), encoding="utf-8")

    comp_lines = [
        "% Generated by scripts/generate_decomposition_outputs.py. Do not edit.",
        r"\begin{table}", r"\caption{Annual applicant-origin concentration}",
        r"\label{tab:annual-origin-composition}", r"\centering", r"\small",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrrr@{}}", r"\toprule",
        r"Year & Destination & Origins & Top 1, \% & Top 5, \% & HHI & Gini \\", r"\midrule",
    ]
    for row in sorted(compositions, key=lambda item: (int(item["year"]), item["destination_code"])):
        comp_lines.append(
            f"{row['year']} & {row['destination_country']} & {row['represented_origins']} & "
            f"{percent(row['top_1_share'])} & {percent(row['top_5_share'])} & "
            f"{float(row['hhi_0_1']):.3f} & {float(row['gini']):.3f} \\\\"
        )
    comp_lines += [
        r"\bottomrule", r"\end{tabular*}",
        r"\parbox{0.96\textwidth}{\scriptsize Notes: Shares use all positive recorded decisions represented for the stated destination and year. HHI is reported on the 0--1 scale.}",
        r"\end{table}", "",
    ]
    annual_composition_path.write_text("\n".join(comp_lines), encoding="utf-8")

    def coordinates(field: str) -> str:
        return " ".join(f"({row['year']},{float(row[field]) * 100:.8f})" for row in annual_decomposition)

    figure = "\n".join([
        "% Generated by scripts/generate_decomposition_outputs.py. Do not edit.",
        r"\begin{tikzpicture}",
        r"\begin{axis}[width=0.88\textwidth,height=0.52\textwidth,xlabel={Year},ylabel={AU minus NZ difference (percentage points)},xtick={2022,2023,2024,2025},grid=major,legend style={font=\small,draw=none,at={(0.5,-0.22)},anchor=north,legend columns=2}]",
        rf"\addplot[black,thick,mark=*] coordinates {{{coordinates('observed_gap')}}};",
        r"\addlegendentry{Observed matched-support gap}",
        rf"\addplot[blue!75!black,thick,mark=square*] coordinates {{{coordinates('rate_component')}}};",
        r"\addlegendentry{Rate component}",
        rf"\addplot[red!75!black,thick,mark=triangle*] coordinates {{{coordinates('composition_component')}}};",
        r"\addlegendentry{Composition component}",
        r"\addplot[gray,dashed] coordinates {(2022,0) (2025,0)};",
        r"\end{axis}", r"\end{tikzpicture}", "",
    ])
    figure_path.write_text(figure, encoding="utf-8")
    return {
        "common_weight_table": standards_path,
        "annual_composition_table": annual_composition_path,
        "decomposition_figure": figure_path,
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--result-dir", type=Path, default=PROJECT_ROOT / "data/results/decomposition")
    parser.add_argument("--manifest", type=Path, default=PROJECT_ROOT / "data/results/manifests/16_composition_decomposition.json")
    parser.add_argument("--table-dir", type=Path, default=PROJECT_ROOT / "article/tables")
    parser.add_argument("--figure-dir", type=Path, default=PROJECT_ROOT / "article/figures")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    outputs = generate_outputs(
        result_dir=args.result_dir, manifest_path=args.manifest,
        table_dir=args.table_dir, figure_dir=args.figure_dir,
    )
    print("Composition-decomposition publication outputs written:")
    for path in outputs.values():
        print(f"- {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
